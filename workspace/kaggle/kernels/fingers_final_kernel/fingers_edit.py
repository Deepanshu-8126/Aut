import os, glob, subprocess, shutil, json
from pathlib import Path

roots=glob.glob('/kaggle/input/**/captions.ass',recursive=True)
assert len(roots)==1, f'Cannot find unique input package: {roots}'
src=Path(roots[0]).parent
out=Path('/kaggle/working'); os.chdir(out)
shutil.copy(src/'captions.ass',out/'captions.ass')
os.makedirs('fonts',exist_ok=True); shutil.copy(src/'Inter-Black.ttf',out/'fonts/Inter-Black.ttf')
# Seven shots: three new Kaggle LTX clips, the conceptual cutaway, and a
# pre-existing simplified vessel diagram. Re-use narration/music/SFX mix once.
inputs=[('soak.mp4',0,3.20),('reveal.mp4',1.40,2.58),('cutaway.png',0,2.97),('diagram_source.mp4',8.75,5.11),('grip.mp4',0,4.58),('reveal.mp4',0,3.26),('soak.mp4',0.85,3.90)]
cmd=['ffmpeg','-y','-hide_banner','-loglevel','warning','-filter_complex_threads','1']
for i,(name,start,dur) in enumerate(inputs):
    if name.endswith('.png'): cmd+=['-loop','1','-framerate','30','-t',str(dur),'-i',str(src/name)]
    else: cmd+=['-i',str(src/name)]
cmd+=['-i',str(src/'mix.wav')]
filters=[]
for i,(name,start,dur) in enumerate(inputs):
    filters.append(f'[{i}:v]trim=start={start}:duration={dur},setpts=PTS-STARTPTS,fps=30,scale=1080:1920:force_original_aspect_ratio=increase:flags=lanczos,crop=1080:1920,setsar=1,format=yuv420p[v{i}]')
filters.append(''.join(f'[v{i}]' for i in range(7))+'concat=n=7:v=1:a=0[sequence]')
filters.append("[sequence]subtitles=filename=captions.ass:fontsdir=fonts[vout]")
cmd+=['-filter_complex',';'.join(filters),'-map','[vout]','-map','7:a:0','-t','25.6','-c:v','libx264','-preset','veryfast','-crf','20','-pix_fmt','yuv420p','-c:a','aac','-b:a','192k','-movflags','+faststart',str(out/'Fingers_Short_1080p_REVIEW.mp4')]
print('Rendering complete edit on Kaggle...',flush=True)
subprocess.run(cmd,check=True)
p=out/'Fingers_Short_1080p_REVIEW.mp4'
subprocess.run(['ffmpeg','-v','error','-i',str(p),'-f','null','-'],check=True)
print('Full decode passed',flush=True)
subprocess.run(['ffprobe','-v','error','-show_entries','format=duration:stream=codec_name,width,height,r_frame_rate','-of','json',str(p)],check=True)
subprocess.run(['ffmpeg','-hide_banner','-i',str(p),'-filter_complex','ebur128=peak=true','-f','null','-'],check=True)
for name in ['captions.srt','thumbnail.png','script.txt','PLAN_SOUND.md']:
    shutil.copy(src/name,out/name)
(out/'REVIEW_NOTES.txt').write_text('FUNCYOUS FINGERS - EDITED REVIEW CUT\nNew character scenes generated by LTX 2.5 on private Kaggle kernel funcyous-fingers-ltx-motion-test. The fingertip cutaway is a simplified AI concept, not a literal anatomical model. Vessel diagram simplified. The possible wet-grip benefit is not a settled evolutionary explanation. Output is 1080x1920 but source motion is 512x896, upscaled. English am_adam voice with existing #464 bed and planned SFX. Captions are machine-aligned. Audio, full-frame hand accuracy, captions, music/SFX rights and scientific review require a human watch/listen before publication. No promise of performance.\n')
print('KAGGLE EDIT COMPLETE',flush=True)
